/**
 * Template field patterns keep their Python meaning (reviews I4, I15, A7).
 * The expected results are what Python's re.fullmatch answers (computed with
 * python3), as the Django version matched them.
 */
import { describe, expect, it } from "vitest";
import { pythonFullmatch } from "./python-regex";

describe("pythonFullmatch", () => {
  it.each([
    ["(?i)kst-\\d{4}", "KST-1234", true],
    ["(?i)kst-\\d{4}", "kst-1234", true],
    ["(?i)kst-\\d{4}", "KST-123", false],
    ["(?i)kst-\\d{4}", "KST-12345", false],
    ["\\d{4}", "1234", true],
    ["\\d{4}", "١٢٣٤", true],
    ["\\d{4}", "12a4", false],
    ["\\d{4}", "1234\n", false],
    ["(?a)\\d{4}", "1234", true],
    ["(?a)\\d{4}", "١٢٣٤", false],
    ["\\w+", "Kostenträger", true],
    ["\\w+", "abc_1", true],
    ["\\w+", "a-b", false],
    ["\\w+", "Ⅻ", true],
    ["[\\w-]+", "a-b", true],
    ["[\\w-]+", "ä-ö", true],
    ["[\\w-]+", "a b", false],
    ["\\s?x", " x", true],
    ["\\s?x", "\u001cx", true],
    ["\\s?x", "﻿x", false],
    ["\\s?x", "x", true],
    ["\\AKST\\Z", "KST", true],
    ["\\AKST\\Z", "KST\n", false],
    ["KST$", "KST", true],
    ["^KST$", "KST", true],
    ["(?P<p>[A-Z]{2})-(?P=p)", "AB-AB", true],
    ["(?P<p>[A-Z]{2})-(?P=p)", "AB-CD", false],
    ["a{,2}", "", true],
    ["a{,2}", "aa", true],
    ["a{,2}", "aaa", false],
    ["a{,}", "aaaa", true],
    ["a{2}", "aa", true],
    ["a{2}", "a", false],
    ["{x}", "{x}", true],
    ["a{}", "a{}", true],
    ["x}", "x}", true],
    ["[]a]+", "]a]", true],
    ["[]a]+", "b", false],
    ["[^]a]", "b", true],
    ["[^]a]", "]", false],
    ["(?x) \\d{2} # two digits", "12", true],
    ["(?x) \\d{2} # two digits", "1 2", false],
    ["(?x)[ ]a", " a", true],
    ["(?x)[ ]a", "a", false],
    ["(?s)a.b", "a\nb", true],
    ["a.b", "a\nb", false],
    ["a.b", "a\rb", true],
    ["a.b", "a-b", true],
    ["(?i:ab)c", "ABc", true],
    ["(?i:ab)c", "ABC", false],
    ["\\bKST\\b", "KST", true],
    ["K\\.T", "K.T", true],
    ["K\\.T", "KxT", false],
    ["K\\-T", "K-T", true],
    ["K\\:T", "K:T", true],
    ["\\x41Ä\\U0001F600", "AÄ😀", true],
    ["\\101", "A", true],
    ["\\0", "\u0000", true],
    ["(a)\\1", "aa", true],
    ["(a)\\1", "ab", false],
    ["(?#note)ab", "ab", true],
    ["(?i)straße", "STRASSE", false],
    ["(?i)straße", "Straße", true],
    ["(?i)straße", "STRAßE", true],
    ["[A-Z]{2}\\d{2}", "DE12", true],
    ["[A-Z]{2}\\d{2}", "de12", false],
    ["\\D+", "abc", true],
    ["\\D+", "a1", false],
    ["[\\D]+", "abc", true],
    ["[\\D]+", "a1", false],
    ["\\W", "-", true],
    ["\\W", "a", false],
    ["\\S+", "ab", true],
    ["\\S+", "a b", false],
    // (?a) with (?i): only ASCII letters fold
    ["(?ai)[A-Z]{3}-\\d{4}", "KST-1234", true],
    ["(?ai)[A-Z]{3}-\\d{4}", "kst-1234", true],
    ["(?ai)[A-Z]{3}-\\d{4}", "İST-1234", false],
    ["(?ai)kst", "KST", true],
    ["(?ai)k", "\u212a", false],
    ["(?ai)s", "ſ", false],
    ["(?ai)[^a-z]", "A", false],
    ["(?ia)[a-z]+", "ÄB", false],
    ["(?ai)[\\u0131]", "I", false],
    // Python's own case-insensitive matches
    ["(?i)[A-Z]{3}-\\d{4}", "İST-1234", true],
    ["(?i)[A-Z]{3}-\\d{4}", "ıST-1234", true],
    ["(?i)i", "İ", true],
    ["(?i)i", "ı", true],
    ["(?i)I", "ı", true],
    ["(?i)ı", "İ", true],
    ["(?i)İ", "i", true],
    ["(?i)[h-j]", "İ", true],
    ["(?i)[^i]", "İ", false],
    ["(?i)[^A-Z]", "ı", false],
    ["(?i)[\\u0131]", "I", true],
    ["i", "I", false],
    ["(?i)k", "\u212a", true],
    ["(?i)[a-z]", "\u212a", true],
    ["(?i)[^k]", "\u212a", false],
    ["(?i)s", "ſ", true],
    ["(?i)[r-t]", "ſ", true],
    ["(?i)\\u03c3", "ς", true],
    ["(?i)\\u00b5", "μ", true],
    ["(?i)\\u0390", "ΐ", true],
    ["(?i)\\ufb05", "ﬆ", true],
    ["(?i)\\u01c5", "Ǆ", true],
    ["(?i)\\u13a0", "ꭰ", true],
    ["(?i)\\u1e9e", "ß", true],
    ["(?i)İ", "i\u0307", false],
    ["(?i)[\\u0100-\\u017f]", "\u212a", false],
    ["(?i)(a)\\1", "aA", true],
    ["(?i:(a))\\1", "aA", false],
    // class escapes inside classes
    ["[\\W_]+", "-", true],
    ["[\\W_]+", "_", true],
    ["[\\W_]+", "!", true],
    ["[\\W_]+", "a", false],
    ["[^\\W\\d_]+", "Kostenträger", true],
    ["[^\\W\\d_]+", "a1", false],
    ["[^\\W\\d_]+", "a_", false],
    ["[\\s\\d]+", " 1\t2", true],
    ["[\\S]+", "a b", false],
    ["(?a)[\\w]+", "ä", false],
    ["(?a)[\\W]", "ä", true],
    ["[\\w.-]+", "a.b-c", true],
    ["[A-Z\\d]{2}", "A1", true],
    // scoped flags
    ["(?m:^KST$)", "KST", true],
    ["(?m:^KST$)", "KST\n", false],
    ["(?i:a(?-i:b))", "Ab", true],
    ["(?i:a(?-i:b))", "AB", false],
    ["(?s:.)", "\n", true],
    ["(?x:a b) c", "ab c", true],
    ["(?a:\\d)", "١", false],
    ["(?i)a(?a:k)", "AK", true],
    ["(?i)a(?a:k)", "A\u212a", false],
    ["(?i)a(?-i:k)", "AK", false],
    ["a(?i:k)", "a\u212a", true],
    ["(?i:i)I", "İI", true],
    // back-references to groups that always take part
    ["(?P<prefix>KST)-(?P=prefix)", "KST-KST", true],
    ["(a)(b)\\2", "abb", true],
    ["(a)(b)\\2", "aba", false],
    ["((a)b)\\2", "aba", true],
    ["(a)+\\1", "aaa", true],
  ] as const)("%s on %j is %s, as in Python", (pattern, value, expected) => {
    expect(pythonFullmatch(pattern)?.test(value)).toBe(expected);
  });

  // Invalid in Python, or without a JavaScript form: refused at template save.
  // A back-reference to a group that may not take part fails in Python and
  // matches empty in JavaScript, so it is refused too.
  it.each([
    "a++",
    "(?>a)",
    "\\q",
    "(?L)a",
    "[",
    "a)",
    "(a\\1)",
    "(?P<prefix>KST)?(?P=prefix)-\\d{4}",
    "(a)|\\1",
    "(a)?\\1",
    "(a)*\\1",
    "(a){0,2}\\1",
    "(?:(a)|b)\\1",
    "(?=(a))\\1a",
  ])("%s has no translation", (pattern) => {
    expect(pythonFullmatch(pattern)).toBeNull();
  });
});
